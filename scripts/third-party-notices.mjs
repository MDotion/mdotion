/**
 * Writes THIRD_PARTY_NOTICES.md: the license text of every npm package that is
 * bundled into the extension (extension host + webview). The MIT and BSD
 * licenses of those packages require their notices to ship with the bundles.
 *
 *   npm run notices
 *
 * The bundles are analysed with esbuild's metafile, so only code that really
 * ends up in dist/ is listed (dev dependencies and unused files are not).
 */
import * as esbuild from 'esbuild';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

async function bundledInputs(entryPoint, options = {}) {
  const result = await esbuild.build({
    entryPoints: [path.join(root, entryPoint)],
    bundle: true,
    write: false,
    metafile: true,
    logLevel: 'silent',
    outdir: path.join(root, '.notices-tmp'),
    ...options,
  });
  return Object.keys(result.metafile.inputs);
}

/** `node_modules/@scope/name/...` → package directory, for the innermost node_modules. */
function packageDir(input) {
  const marker = 'node_modules/';
  const index = input.lastIndexOf(marker);
  if (index < 0) {
    return null;
  }
  const rest = input.slice(index + marker.length).split('/');
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0];
  return path.join(root, input.slice(0, index + marker.length), name);
}

function licenseText(dir) {
  const file = readdirSync(dir).find((entry) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(entry));
  return file ? readFileSync(path.join(dir, file), 'utf8').trim() : null;
}

const inputs = [
  ...(await bundledInputs('src/extension.ts', { platform: 'node', format: 'cjs', external: ['vscode'] })),
  ...(await bundledInputs('webview/src/main.tsx', {
    platform: 'browser',
    format: 'iife',
    jsx: 'automatic',
    loader: { '.css': 'empty' },
  })),
];

const packages = new Map();
for (const input of inputs) {
  const dir = packageDir(input);
  if (!dir || packages.has(dir) || !existsSync(path.join(dir, 'package.json'))) {
    continue;
  }
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  packages.set(dir, {
    name: pkg.name,
    version: pkg.version,
    license: typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN'),
    repository: typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url,
    text: licenseText(dir),
  });
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const missing = sorted.filter((pkg) => !pkg.text);

const lines = [
  '# Third-party notices',
  '',
  'MDotion is released under the [MIT License](LICENSE). The extension bundles the',
  'following open-source packages, whose licenses are reproduced below.',
  '',
  '_Generated by `npm run notices` from the production bundles — do not edit by hand._',
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...sorted.map((pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license} |`),
  '',
];
for (const pkg of sorted) {
  lines.push('---', '', `## ${pkg.name}@${pkg.version}`, '', `License: ${pkg.license}`);
  if (pkg.repository) {
    lines.push(`Source: ${pkg.repository.replace(/^git\+/, '')}`);
  }
  lines.push('', '```text', pkg.text ?? `${pkg.license} (no license file shipped in the package)`, '```', '');
}
writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));

const licenses = [...new Set(sorted.map((pkg) => pkg.license))].sort();
console.log(`[mdotion] THIRD_PARTY_NOTICES.md: ${sorted.length} packages (${licenses.join(', ')})`);
if (missing.length > 0) {
  console.warn(`[mdotion] no license file in: ${missing.map((pkg) => pkg.name).join(', ')}`);
}
